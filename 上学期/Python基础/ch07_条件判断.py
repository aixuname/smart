# ============================================================
# 第七章：条件判断
# 目标：让程序根据不同情况做不同的事
# ============================================================

# ---- 1. if / elif / else ----
# if     ：如果满足条件，就执行
# elif   ：否则如果满足另一个条件，就执行（可以写多个）
# else   ：以上都不满足时执行（可省略）

score = 85

if score >= 90:
    print("优秀")
elif score >= 80:
    print("良好")
elif score >= 60:
    print("及格")
else:
    print("不及格")

# 注意：从上往下判断，命中第一个满足的条件后，后面的不再执行
# 所以上面的 85 会输出"良好"，不会继续判断 60

# ---- 2. 简单的 if ----
age = 20
if age >= 18:
    print("成年了")

# ---- 3. 嵌套条件 ----
# 条件里还可以套条件
num = 15
if num > 0:
    if num % 2 == 0:      # % 是取余，等于 0 就是偶数
        print("正偶数")
    else:
        print("正奇数")
else:
    print("非正数")

# ---- 4. 三元表达式 ----
# 一行写完的简单 if-else
n = 10
result = "偶数" if n % 2 == 0 else "奇数"
print(result)

# ---- 5. 常见错误提醒 ----
# 1) 条件后面要加冒号 :
# 2) 属于 if 块的代码要缩进
# 3) 判断相等用 ==，不是 =
