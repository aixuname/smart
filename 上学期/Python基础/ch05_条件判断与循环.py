# 第五章：条件判断与循环
# 目标：让程序根据不同情况作出选择，并能够重复执行任务
# ============================================================

# ============================================================
# 第一部分：条件判断
# ============================================================

# ---- 1. if / elif / else ----
# if     ：如果满足条件，就执行
# elif   ：否则如果满足另一个条件，就执行（可以写多个）
# else   ：以上都不满足时执行（可省略）

score = 85

if score >= 90:
    print("优秀")
elif score >= 80:
    print("良好")
elif score >= 60:
    print("及格")
else:
    print("不及格")

# 注意：从上往下判断，命中第一个满足的条件后，后面的不再执行
# 所以上面的 85 会输出"良好"，不会继续判断 60

# ---- 2. 简单的 if ----
age = 20
if age >= 18:
    print("成年了")

# ---- 3. 嵌套条件 ----
# 条件里还可以套条件
num = 15
if num > 0:
    if num % 2 == 0:      # % 是取余，等于 0 就是偶数
        print("正偶数")
    else:
        print("正奇数")
else:
    print("非正数")

# ---- 4. 三元表达式 ----
# 一行写完的简单 if-else
n = 10
result = "偶数" if n % 2 == 0 else "奇数"
print(result)

# ---- 5. 常见错误提醒 ----
# 1) 条件后面要加冒号 :
# 2) 属于 if 块的代码要缩进
# 3) 判断相等用 ==，不是 =

# ============================================================
# 第二部分：循环
# ============================================================

# ---- 1. for 循环 ----
# 一个一个取出可迭代对象里的元素
for i in [1, 2, 3, 4, 5]:
    print(i)

# 配合 range() 生成数字序列
# range(n)     生成 0 到 n-1
# range(a, b)  生成 a 到 b-1
print("--- range 示例 ---")
for i in range(3):          # 0, 1, 2
    print(i)

for i in range(2, 6):       # 2, 3, 4, 5
    print(i)

# 遍历字符串
for char in "Python":
    print(char)

# ---- 2. while 循环 ----
# 只要条件为真，就一直重复
count = 0
while count < 3:
    print(f"第 {count} 次")
    count += 1            # 每次让 count 加 1，否则会死循环！

# ---- 3. break 和 continue ----
# break     ：立即结束整个循环
# continue  ：跳过本次，进入下一轮

print("--- break ---")
for i in range(10):
    if i == 3:
        break             # 到 3 就停止
    print(i)              # 输出 0 1 2

print("--- continue ---")
for i in range(5):
    if i == 2:
        continue          # 跳过 2
    print(i)              # 输出 0 1 3 4

# ---- 4. 循环嵌套 ----
# 打印乘法口诀表（外层循环控制行，内层循环控制列）
for i in range(1, 10):
    for j in range(1, i + 1):
        print(f"{j}×{i}={i*j}", end="\t")   # end 让 print 不换行
    print()               # 一行打完换行

# ---- 5. for-else ----
# 如果循环正常结束（没被 break 打断），就执行 else
for i in range(3):
    print(i)
else:
    print("循环正常结束")
