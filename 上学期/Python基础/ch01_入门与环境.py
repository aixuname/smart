# ---- 1. 注释 ----
# 井号后面的内容都是注释，Python 不会执行它
# 注释是用来给人看的，解释代码在做什么

# ---- 2. 输出 print() ----
# print() 会把内容显示在屏幕上
print("Hello, Python!")          # 输出一句话
print(123)                        # 输出数字
print("1 + 1 =", 1 + 1)          # 逗号可以一次输出多个东西

# ---- 3. 输入 input() ----
# input() 会等待你在键盘上输入，输入的内容是"字符串"类型
# 运行后，在下面输入你的名字，然后回车
name = input("请输入你的名字：")   # 括号里的文字是提示语
print("你好，", name)

# ---- 4. 缩进非常重要 ----
# Python 用缩进（行首的空格）来区分代码块
# 下面 if 后面的两行都要缩进，表示它们属于同一个"块"
age = 20
if age >= 18:              # 这一行结尾有冒号
    print("你已经成年了")    # 缩进了，属于 if 块
    print("可以考驾照了")    # 也是 if 块的一部分
print("这句话不受 if 影响")  # 顶格写，不在 if 块里
